#!/usr/bin/env node
// Copies the hook scripts in assets/ into a TypeScript module.
//
// The released binary is one file produced by `bun build --compile`, so only
// what the JavaScript bundle imports travels with it. A .sh read from disk at
// install time would not exist on the machine that downloaded the binary, and
// the hook has to be written there. This copies the bytes into a module the
// bundle carries, while the scripts stay real shell files that an editor
// highlights and shellcheck can read.
//
// Run it after editing either script. A unit test compares the module against
// the files, so forgetting to run it fails the suite instead of shipping.
//
// Usage: node scripts/generate-hook-assets.mjs

import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const OUTPUT = 'src/adapters/cli/install/hooks/hook-scripts.generated.ts'

const SCRIPTS = [
  { constant: 'CLAUDE_HOOK_SCRIPT', source: 'assets/hook_claude.sh', client: 'Claude Code' },
  { constant: 'CODEX_HOOK_SCRIPT', source: 'assets/hook_codex.sh', client: 'Codex' },
]

const declarations = await Promise.all(
  SCRIPTS.map(async ({ constant, source, client }) => {
    const contents = await readFile(join(ROOT, source), 'utf8')

    // JSON.stringify rather than a template literal: the scripts are full of
    // backticks, `${...}` and backslashes, and every one of them would need an
    // escape that a later edit could forget.
    return `/** The hook ${client} runs, byte for byte from \`${source}\`. */\nexport const ${constant} = ${JSON.stringify(contents)}\n`
  }),
)

const header = `// Generated by scripts/generate-hook-assets.mjs. Do not edit by hand:
// edit the scripts under assets/ and run \`pnpm generate:hooks\`.
`

await writeFile(join(ROOT, OUTPUT), `${header}\n${declarations.join('\n')}`, 'utf8')

console.log(`Wrote ${OUTPUT}`)
