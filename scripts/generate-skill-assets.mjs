#!/usr/bin/env node
// Copies the skill under assets/ into a TypeScript module.
//
// Same reason as the hook scripts: the released binary is one file produced by
// `bun build --compile`, so only what the JavaScript bundle imports travels
// with it. A SKILL.md read from disk at install time would not exist on the
// machine that downloaded the binary, and the skill has to be written there.
// This copies the bytes into a module the bundle carries, while the skill stays
// a real directory of Markdown that an editor renders and a person can review.
//
// Every file under the source directory is carried, whatever its depth, so
// adding a reference document is an edit to assets/ and a re-run of this.
//
// Run it after editing the skill. A unit test compares the module against the
// files, so forgetting to run it fails the suite instead of shipping.
//
// Usage: node scripts/generate-skill-assets.mjs

import { readFile, readdir, writeFile } from 'node:fs/promises'
import { dirname, join, relative, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const SOURCE = 'assets/skill-router-metadata'
const OUTPUT = 'src/adapters/cli/install/skill/skill-files.generated.ts'

/** The directory name is the skill's name: it is how an agent finds and invokes it. */
const NAME = SOURCE.split('/').pop()

const directory = join(ROOT, SOURCE)
const found = await readdir(directory, { recursive: true, withFileTypes: true })

const paths = found
  .filter((entry) => entry.isFile())
  // Forward slashes whatever the platform this ran on: the key is data in a
  // generated file that a Windows machine may read, and the installer splits it
  // back apart rather than trusting a separator baked in here.
  .map((entry) => relative(directory, join(entry.parentPath, entry.name)).split(sep).join('/'))
  .sort()

if (paths.length === 0) {
  throw new Error(`${SOURCE} has no files to carry.`)
}

if (!paths.includes('SKILL.md')) {
  throw new Error(`${SOURCE} has no SKILL.md, so no agent would recognize it as a skill.`)
}

const files = await Promise.all(
  paths.map(async (path) => {
    const contents = await readFile(join(directory, ...path.split('/')), 'utf8')

    // JSON.stringify rather than a template literal: the skill is Markdown full
    // of backticks and `${...}` inside its examples, and every one of them would
    // need an escape that a later edit could forget.
    return `  ${JSON.stringify(path)}: ${JSON.stringify(contents)},`
  }),
)

const module = `// Generated by scripts/generate-skill-assets.mjs. Do not edit by hand:
// edit the files under ${SOURCE}/ and run \`pnpm generate:skill\`.

/** The directory the skill is installed as, which is also how an agent invokes it. */
export const SKILL_NAME = ${JSON.stringify(NAME)}

/** Every file of the skill, keyed by its path relative to the skill directory. */
export const SKILL_FILES: Readonly<Record<string, string>> = {
${files.join('\n')}
}
`

await writeFile(join(ROOT, OUTPUT), module, 'utf8')

console.log(`Wrote ${OUTPUT} (${String(paths.length)} files from ${SOURCE})`)
